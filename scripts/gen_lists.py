import re, json, sys
src = open(sys.argv[1], encoding='utf-8').read()
lists, var2title, order = {}, {}, []
for m in re.finditer(r'^\$(\w+)\s*=\s*Ensure-List\s+"([^"]+)"\s+"([^"]+)"', src, re.M):
    var, title, url = m.groups()
    var2title[var] = title
    lists[title] = {"title": title, "url": url, "fields": []}
    order.append(title)
choice_vars = {"notify": ["Teams", "Outlook", "Teams and Outlook"]}
def parse_arr(s):
    s = s.strip()
    if s.startswith("$"): return choice_vars[s[1:]]
    if s.startswith("(@('Project default') + $notify)"): return ["Project default"] + choice_vars["notify"]
    return re.findall(r"'([^']*)'", s)
for line in src.splitlines():
    m = re.match(r'^(Text|Note|Choice|DateF|DateTimeF|UserF|BoolF|UrlF|NumberF|LookupF|LookupMultiF)\s+\$(\w+)\s+"([^"]+)"\s+"([^"]+)"(.*)$', line.strip())
    if not m: continue
    kind, var, name, disp, rest = m.groups()
    f = {"name": name, "display": disp}
    rest = rest.strip()
    if kind == "Text": f["type"] = "Text"
    elif kind == "Note": f["type"] = "Note"; f["rich"] = "-Rich" in rest
    elif kind == "Choice":
        mm = re.match(r'(\(@\(.*?\)\s*\+\s*\$notify\)|@\(.*?\)|\$\w+)\s+"([^"]*)"', rest)
        f["type"] = "Choice"; f["choices"] = parse_arr(mm.group(1)); f["default"] = mm.group(2)
    elif kind == "DateF": f["type"] = "Date"
    elif kind == "DateTimeF": f["type"] = "DateTime"
    elif kind == "UserF": f["type"] = "UserMulti" if "-Multi" in rest else "User"
    elif kind == "BoolF": f["type"] = "Boolean"
    elif kind == "UrlF": f["type"] = "URL"
    elif kind == "NumberF": f["type"] = "Number"
    elif kind in ("LookupF", "LookupMultiF"):
        f["type"] = "Lookup" if kind == "LookupF" else "LookupMulti"; f["lookupList"] = var2title[rest.lstrip("$").strip()]
    lists[var2title[var]]["fields"].append(f)
out = {"_about": "MinuteMate SharePoint lists. Generated from provisioning/Setup-MinuteMate.ps1; read by the Set up MinuteMate flow (flows/00-set-up-minutemate.md) and the website's setup check.",
       "lists": [lists[t] for t in order]}
json.dump(out, open(sys.argv[2], 'w', encoding='utf-8'), indent=2, ensure_ascii=False)
print(len(order), "lists", sum(len(l["fields"]) for l in out["lists"]), "fields")

# ---- add SharePoint field schema XML (same as the PowerShell helpers) ----
from xml.sax.saxutils import escape
def xml(f):
    n, d = f["name"], escape(f["display"], {"'": "&apos;"})
    base = f"Name='{n}' StaticName='{n}' DisplayName='{d}'"
    t = f["type"]
    if t == "Text": return f"<Field Type='Text' {base} MaxLength='255' />"
    if t == "Note": return f"<Field Type='Note' {base} NumLines='10' " + ("RichText='TRUE' RichTextMode='FullHtml'" if f.get("rich") else "RichText='FALSE'") + " />"
    if t == "Choice":
        c = "".join(f"<CHOICE>{escape(x)}</CHOICE>" for x in f["choices"])
        return f"<Field Type='Choice' {base} Format='Dropdown'><Default>{escape(f['default'])}</Default><CHOICES>{c}</CHOICES></Field>"
    if t == "Date": return f"<Field Type='DateTime' {base} Format='DateOnly' />"
    if t == "DateTime": return f"<Field Type='DateTime' {base} Format='DateTime' />"
    if t == "User": return f"<Field Type='User' {base} UserSelectionMode='PeopleOnly' />"
    if t == "UserMulti": return f"<Field Type='UserMulti' Mult='TRUE' {base} UserSelectionMode='PeopleOnly' />"
    if t == "Boolean": return f"<Field Type='Boolean' {base}><Default>0</Default></Field>"
    if t == "URL": return f"<Field Type='URL' {base} Format='Hyperlink' />"
    if t == "Number": return f"<Field Type='Number' {base} Decimals='0'><Default>0</Default></Field>"
    if t == "Lookup": return f"<Field Type='Lookup' {base} List='{{ListId:{f['lookupList']}}}' ShowField='Title' />"
    if t == "LookupMulti": return f"<Field Type='LookupMulti' Mult='TRUE' {base} List='{{ListId:{f['lookupList']}}}' ShowField='Title' />"
    raise ValueError(t)
for l in out["lists"]:
    for f in l["fields"]: f["schemaXml"] = xml(f)
json.dump(out, open(sys.argv[2], 'w', encoding='utf-8'), indent=2, ensure_ascii=False)

# ---- website: required columns per list, for the Setup check page ----
import os
web_js = os.path.join(os.path.dirname(os.path.abspath(sys.argv[2])), "..", "web", "js", "schema.js")
required = {l["url"]: {"title": l["title"], "columns": [f["name"] for f in l["fields"]]} for l in out["lists"]}
with open(os.path.normpath(web_js), "w", encoding="utf-8") as fh:
    fh.write("// Generated by scripts/gen_lists.py from provisioning/Setup-MinuteMate.ps1. Do not edit by hand.\n")
    fh.write("// The website's Setup check compares the SharePoint site against this list.\n")
    fh.write("export const REQUIRED = " + json.dumps(required, indent=2) + ";\n")
print("wrote", os.path.normpath(web_js))
